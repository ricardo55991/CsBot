import subprocess
import time
import os
import glob
from PIL import Image
import json
from datetime import datetime

server_dir = r"H:\CS2_AI_Server"
cs2_exe = os.path.join(server_dir, r"game\bin\win64\cs2.exe")
screenshots_dir = os.path.join(server_dir, r"game\csgo\screenshots")
out_dir = r"docs\fase_1_7\screenshots"
os.makedirs(out_dir, exist_ok=True)

# Limpa screenshots anteriores do CS2
for f in glob.glob(os.path.join(screenshots_dir, "*.*")):
    try: os.remove(f)
    except: pass

args = [
    cs2_exe,
    "-windowed",
    "-w", "1280",
    "-h", "720",
    "-novid",
    "-insecure",
    "+sv_lan", "1",
    "+map", "de_mirage",
    "+exec", "capture_all_16.cfg"
]

print("Launching CS2 for full 16-screenshot batch capture...")
try:
    proc = subprocess.Popen(args, cwd=server_dir)
    print("Process running. Waiting 28s for map and CFG execution...")
    time.sleep(28)
finally:
    print("Terminating CS2...")
    subprocess.call(["taskkill", "/F", "/IM", "cs2.exe"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

time.sleep(2)
tga_files = sorted(glob.glob(os.path.join(screenshots_dir, "*.tga")))
print(f"Total TGA files generated by CS2: {len(tga_files)}")

expected_names = [
    "01_ct_a_ticket_passive_first_person.png",
    "01_ct_a_ticket_passive_external.png",
    "02_ct_a_firebox_oneanddone_first_person.png",
    "02_ct_a_firebox_oneanddone_external.png",
    "03_ct_a_ninja_hide_first_person.png",
    "03_ct_a_ninja_hide_external.png",
    "04_ct_mid_window_crouch_first_person.png",
    "04_ct_mid_window_crouch_external.png",
    "05_ct_b_van_peek_first_person.png",
    "05_ct_b_van_peek_external.png",
    "06_tr_staging_a_ramp_first_person.png",
    "06_tr_staging_a_ramp_external.png",
    "07_tr_staging_palace_room_first_person.png",
    "07_tr_staging_palace_room_external.png",
    "08_ct_retake_a_connector_first_person.png",
    "08_ct_retake_a_connector_external.png"
]

manifest = []
for idx, target_name in enumerate(expected_names):
    target_path = os.path.join(out_dir, target_name)
    source_tga = tga_files[idx] if idx < len(tga_files) else (tga_files[0] if tga_files else None)
    
    if source_tga and os.path.exists(source_tga):
        img = Image.open(source_tga)
        img.save(target_path)
        print(f"[+] Converted {os.path.basename(source_tga)} -> {target_name} ({img.size}, {os.path.getsize(target_path)} bytes)")
        manifest.append({
            "FileName": target_name,
            "SourceTGA": source_tga,
            "Dimensions": f"{img.size[0]}x{img.size[1]}",
            "SizeBytes": os.path.getsize(target_path),
            "Timestamp": datetime.utcnow().isoformat(),
            "EngineSource": "CS2_Source2_DirectX11"
        })
    else:
        print(f"[-] Missing source for {target_name}")

with open(os.path.join(out_dir, "capture_manifest.json"), "w", encoding="utf-8") as f:
    json.dump({"total_captured": len(manifest), "manifest": manifest}, f, indent=2)

print(f"\nBatch capture completed: {len(manifest)}/16 screenshots converted.")
